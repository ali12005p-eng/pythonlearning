import os
import re
from groq import Groq

GROQ_API_KEY = os.getenv("GROQ_API_KEY")

client = Groq(api_key=GROQ_API_KEY)


# =========================
# 🧹 فلترة اللغة العربية فقط (إضافة جديدة)
# =========================

def clean_arabic_text(text: str) -> str:
    # حذف الحروف الإنجليزية
    text = re.sub(r"[A-Za-z]+", "", text)

    # حذف الرموز الغريبة مع الإبقاء على العربية والعلامات الأساسية
    text = re.sub(r"[^\u0600-\u06FF0-9\s\.\،\!\؟\:\-\(\)]", "", text)

    # إزالة التكرار الزائد للمسافات
    text = re.sub(r"\s+", " ", text).strip()

    return text


async def generate_story(history: str):

    prompt = f"""
أنت مدير لعبة RPG احترافية ومتقدمة جداً باللغة العربية الفصحى.

سجل القصة الكامل:

{history}

قواعد إلزامية:

1- إذا كانت هذه بداية قصة جديدة:
- اشرح العالم بشكل ممتع وواضح.
- عرّف اللاعب بشخصيته.
- وضح دوره ومكانه في العالم.
- وضح الهدف الأساسي.
- ابدأ أول مشهد.
- اطلب منه اتخاذ قرار أو تنفيذ تصرف.

2- إذا كانت القصة مستمرة:
- اعتبر رسالة اللاعب فعلاً حقيقياً داخل العالم.
- يجب أن تؤثر قراراته على الأحداث.
- لا تتجاهل أي قرار.
- لا تبدأ قصة جديدة.
- لا تغيّر الشخصيات أو العالم فجأة.
- حافظ على استمرارية الأحداث.

3- تطوير العالم:
- أنشئ شخصيات جانبية تتذكر اللاعب.
- اجعل الشخصيات تتفاعل مع سمعته وأفعاله.
- أضف أسراراً وأحداثاً جانبية.
- أضف أماكن جديدة تدريجياً.
- أضف تحديات ومفاجآت منطقية.

4- نظام الفوز والخسارة:
- لا تنهِ القصة عند الخسارة.
- عند الفشل أظهر العواقب واستمر.
- عند النجاح كافئ اللاعب بمكاسب أو معلومات جديدة.

5- أسلوب الكتابة:
- استخدم العربية الفصحى فقط.
- ممنوع الكلمات الأجنبية.
- ممنوع خلط اللغات.
- ممنوع الأسماء الأجنبية إلا إذا كانت عربية أو خيالية عربية.
- اكتب النص بشكل أدبي وسينمائي.
- اجعل الأحداث مشوقة وطويلة نسبياً.

6- التفاعل:
- لا تضع خيارات مرقمة.
- اسمح للاعب بكتابة أي تصرف.
- اختم دائماً بموقف يحتاج إلى قرار جديد.

7- الذاكرة:
- تذكر جميع الأحداث السابقة.
- تذكر الشخصيات والأماكن.
- تذكر العلاقات والعداوات.
- تذكر المكاسب والخسائر السابقة.

اكتب الرد الآن.
"""

    completion = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {
                "role": "system",
                "content": """
أنت مدير لعبة RPG احترافية.

يجب عليك:

- الحفاظ على استمرارية القصة.
- تذكر جميع الأحداث السابقة.
- جعل العالم يتغير حسب أفعال اللاعب.
- إنشاء شخصيات وأماكن وأحداث مترابطة.
- عدم نسيان الشخصيات المهمة.
- استخدام العربية الفصحى فقط.
- منع الكلمات الأجنبية أو الرموز الغريبة.
- جعل القصة طويلة وممتعة.
- عدم إنهاء القصة بسهولة.
- جعل كل قرار له نتائج مستقبلية.
"""
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.85,
        max_tokens=1400
    )

    # =========================
    # 🧹 تطبيق الفلترة (إضافة فقط)
    # =========================

    raw_text = completion.choices[0].message.content
    cleaned_text = clean_arabic_text(raw_text)

    return cleaned_text
