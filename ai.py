import os
from groq import Groq

GROQ_API_KEY = os.getenv("GROQ_API_KEY")

client = Groq(api_key=GROQ_API_KEY)


async def generate_story(history: str):
    prompt = f"""
أنت مدير لعبة RPG تفاعلية باللغة العربية.

سجل الأحداث الحالي:

{history}

قواعد مهمة جداً:

- إذا كانت هذه بداية قصة جديدة:
    1. اشرح عالم القصة باختصار.
    2. عرف المستخدم بشخصيته ودوره.
    3. وضح هدفه الرئيسي.
    4. ابدأ أول مشهد من القصة.
    5. اطلب منه اتخاذ قرار أو تنفيذ تصرف.

- إذا كانت القصة قد بدأت بالفعل:
    1. اعتبر رسالة المستخدم قراراً أو تصرفاً داخل القصة.
    2. اجعل الأحداث تتغير بناءً على قراره.
    3. لا تتجاهل قراراته.
    4. لا تبدأ قصة جديدة.
    5. حافظ على الشخصيات والأماكن والأحداث السابقة.
    6. أظهر نتائج قراره بشكل منطقي.
    7. اختم دائماً بموقف يحتاج إلى قرار جديد.

- لا تكتب خيارات مرقمة إجبارية.
- اسمح للمستخدم بكتابة أي تصرف يريده.
- اجعل العالم يتفاعل مع أفعاله.
- اجعل القصة ممتعة ومليئة بالمفاجآت.
- لا تنهِ القصة بسرعة.
- تذكر جميع الأحداث السابقة.

اكتب الرد الآن.
"""

    completion = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {
                "role": "system",
                "content": (
                    "أنت مدير لعبة RPG تفاعلية. "
                    "في بداية أي قصة جديدة يجب شرح العالم، "
                    "ودور اللاعب، وهدفه، ثم بدء أول مشهد. "
                    "بعد ذلك يجب أن تتغير الأحداث بناءً على "
                    "تصرفات اللاعب فقط مع الحفاظ على الاستمرارية."
                )
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.9,
        max_tokens=1024
    )

    return completion.choices[0].message.content
