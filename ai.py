import os
from groq import Groq

GROQ_API_KEY = os.getenv("GROQ_API_KEY")

client = Groq(api_key=GROQ_API_KEY)


# 🔥 فلتر قوي لإجبار العربية فقط
SYSTEM_RULES = """
أنت كاتب ومدير لعبة RPG تفاعلية.

قواعد صارمة جداً:
- اكتب باللغة العربية الفصحى فقط.
- ممنوع استخدام أي كلمات إنجليزية نهائياً.
- ممنوع خلط لغات أو حروف أجنبية.
- ممنوع كتابة كلمات مشوهة أو غير مفهومة.
- إذا احتجت مصطلح أجنبي، قم بترجمته للعربية فقط.
- حافظ على أسلوب قصصي سينمائي ممتع.
- لا تكسر القصة أو تغير الأحداث السابقة.
"""


def clean_text(text: str) -> str:
    """
    تنظيف بسيط لأي حروف أجنبية أو رموز غريبة
    بدون التأثير على المعنى الأساسي
    """
    allowed = "ابتثجحخدذرزسشصضطظعغفقكلمنهويىئءةأإآ 0123456789؟!.,:-\n\"'()"

    cleaned = "".join(ch for ch in text if ch in allowed)
    return cleaned


async def generate_story(history: str):

    prompt = f"""
أنت مدير لعبة RPG تفاعلية باللغة العربية.

سجل الأحداث الحالي:

{history}

قواعد مهمة جداً:

- إذا كانت هذه بداية قصة جديدة:
    1. اشرح عالم القصة باختصار.
    2. عرف المستخدم بشخصيته ودوره.
    3. وضح هدفه الرئيسي.
    4. ابدأ أول مشهد من القصة.
    5. اطلب منه اتخاذ قرار أو تنفيذ تصرف.

- إذا كانت القصة قد بدأت بالفعل:
    1. اعتبر رسالة المستخدم قراراً أو تصرفاً داخل القصة.
    2. اجعل الأحداث تتغير بناءً على قراره.
    3. لا تتجاهل قراراته.
    4. لا تبدأ قصة جديدة.
    5. حافظ على الشخصيات والأماكن والأحداث السابقة.
    6. أظهر نتائج قراره بشكل منطقي.
    7. اختم دائماً بموقف يحتاج إلى قرار جديد.

- لا تكتب خيارات مرقمة إجبارية.
- اسمح للمستخدم بكتابة أي تصرف يريده.
- اجعل العالم يتفاعل مع أفعاله.
- اجعل القصة ممتعة ومليئة بالمفاجآت.
- لا تنهِ القصة بسرعة.
- تذكر جميع الأحداث السابقة.

اكتب الرد الآن.
"""

    completion = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {
                "role": "system",
                "content": SYSTEM_RULES
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.9,
        max_tokens=1024
    )

    response = completion.choices[0].message.content

    # 🔥 تنظيف أي لغات أو رموز غريبة قبل الإرسال
    return clean_text(response)
